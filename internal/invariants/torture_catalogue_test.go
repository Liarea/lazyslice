// tortureRoot is the absolute path of testdata/torture.
func tortureRoot() (string, error) {
	root, err := repoRoot()
	if err != nil {
		return "", err
	}
	return filepath.Join(root, "testdata", "torture"), nil
}

// loadTorture is the fixture loader for one schema: the upstream schema, the
// shared generator, the schema's own generator, and the cleanup that takes the
// generator back out again. Four files, in that order, and testdata/torture's
// README.md is the contract.
func (s tortureSchema) load(ctx context.Context, connURL string) error {
	dir, err := tortureRoot()
	if err != nil {
		return err
	}
	for _, path := range []string{
		filepath.Join(dir, s.dir, "schema.sql"),
		filepath.Join(dir, "_common", "fill.sql"),
		filepath.Join(dir, s.dir, "generate.sql"),
		filepath.Join(dir, "_common", "cleanup.sql"),
	} {
		if err := runScript(ctx, connURL, path); err != nil {
			return err
		}
	}
	return nil
}

// runScript sends one .sql file to the database as a single simple query.
//
// It is not psql and it does not need to be: nothing under testdata/torture/ has
// a `COPY ... FROM stdin` block or a backslash command — the schemas are
// pg_dump's `--schema-only` output with its two `\restrict` lines removed, and
// the generators are ordinary statements — so the server's own statement
// splitting is the whole of what is required. testdata/torture/README.md carries
// that as a rule, and a file that broke it would fail here with the server's own
// syntax error and the file's name.
//
// pgx sends a query with no arguments through the simple protocol, which is what
// makes a multi-statement script work at all.
func runScript(ctx context.Context, connURL, path string) error {
	text, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("torture: reading %s: %w", filepath.Base(path), err)
	}
	if strings.TrimSpace(string(text)) == "" {
		return nil
	}
	conn, err := pgx.Connect(ctx, connURL)
	if err != nil {
		return fmt.Errorf("torture: connecting to load %s: %w", filepath.Base(path), err)
	}
	defer func() { _ = conn.Close(context.WithoutCancel(ctx)) }()

	if _, err := conn.Exec(ctx, string(text)); err != nil {
		return fmt.Errorf("torture: %s: %w", filepath.Base(path), err)
	}
	return nil
}
