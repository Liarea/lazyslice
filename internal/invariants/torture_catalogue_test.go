// The ten schemas of testdata/torture/, and the runs `make torture` makes
// against them.
//
// They are here rather than in a package of their own because everything the
// suite needs is here: the binary under test is built once (harness_test.go),
// the two containers are started the same way, and the assertions are the same
// helpers I1, I2, I4 and I6 use against pagila and nasty. A torture suite that
// re-implemented "every foreign key in the target resolves" would be asserting
// something subtly different from the invariant of the same name, which is the
// one thing it must not do.
//
// The build tag is `integration && torture`, so `make integration` does not run
// them: ten real schemas on two containers each is a different unit of work from
// the six invariants, and docs/TORTURE.md records the times. `make torture` is
// the target.

// tortureSchema is one schema under testdata/torture/ and the run made against
// it.
type tortureSchema struct {
	// dir is the directory under testdata/torture/.
	dir string

	// image, when set, is the container image both databases run. Only
	// discourse sets it: its schema needs pgvector.
	image string

	// root is the table the snapshot slices from, and it is not a free choice.
	// The rule, applied to every schema and checked at run time by
	// assertRootIsMostConnected, is: the table with the most foreign-key edges
	// incident to it, counting each declared constraint once, in either
	// direction; ties broken by incoming edges, then by row count, then by name.
	//
	// Discourse is the schema that needs all four terms. `public.users`,
	// `public.uploads` and `public.ad_plugin_house_ads` each have exactly four
	// incoming edges and no outgoing ones, and the fixture's row counts
	// (300/150/20) are what separate them.
	root string
	take int

	// flags are what a first run refused and told the operator to pass, in the
	// order the refusals arrived. Every one of them is in docs/TORTURE.md with
	// the reason it is there.
	flags []string

	// wantExit is the exit code the run must produce, and wantCode the event
	// code that must be in the message. Nine of the ten are 0; mastodon is the
	// tenth, and what it must fail with is as much a part of the suite as the
	// nine successes are.
	wantExit int
	wantCode string

	// mustHoldRows names tables the slice has to reach, each holding at least
	// one row in the target; mustBeSubset the ones it must hold fewer rows of
	// than the source. Same meaning, and same reason for the split, as the two
	// fields of fixture (harness_test.go).
	mustHoldRows []string
	mustBeSubset []string

	// countedRoot and countedTake are I6's slice: a root no selected row can
	// reach as a parent, so that "the root holds exactly --take rows" is true.
	// Empty means the schema contributes no I6 case, which is the honest answer
	// for a schema whose most-connected table is reachable from its own
	// children.
	countedRoot string
	countedTake int
}

